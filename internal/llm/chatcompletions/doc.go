// Package chatcompletions 把 internal/llm 的供应商无关契约翻译为
// Chat Completions wire 协议。
//
// # 职责边界
//
// 本包只做翻译：请求方向的投影、响应方向的装配、错误分类。
// 它不解析工具参数、不执行工具、不做权限裁决、不持久化内容，
// 也不决定一次生成结果是否可以入账。
//
// # 能力边界
//
// 能发送的内容：文本、推理、拒绝、JSON、工具调用、图片（内联字节或
// 绝对 HTTP(S) URL）、内联音频、工具结果。
// 视频、文档、普通文件、opaque 内容，以及来源为资源库引用或供应商
// 文件引用的媒体，都没有对应的 wire 表达：它们会被丢弃，请求照常发送。
//
// 适配器不请求多候选（不发送 n），因此正常情况下只会收到一个候选；
// 收到多个候选属于端点不守约定，按协议错误处理。
//
// # 归一化
//
// 供应商的实际返回与 IR 的规定不一致时，适配器按下面的规则处理：
//   - usage 的 total 原样保留（IR 不要求它等于输入加输出）；
//   - 结果携带工具调用但供应商报“自然停止”时，停止原因归一为 tool_use，
//     原始值保留在 ProviderStopReason 里；
//   - 其余不一致一律作为协议错误，不猜测、不改写。
